#!/usr/bin/env python3
#
# extract_data.py - turn the DSE results (results/<campaign>/*.jsonl, git-ignored) and the build reports
# (build/gemm/soc/<build_id>/) into the small CSV files the report plots read (docs/report/data/*.csv).
#   .venv/bin/python docs/report/tools/extract_data.py      (docs/report/build.sh runs it when results/ exists)
#
# The CSVs are committed, so the report builds from a clean checkout without results/ or build/.
# Hand-written data (not regenerated here) lives in data/manual_*.csv, with its source in a comment line.
#

import collections
import csv
import glob
import json
import math
import os
import re
import statistics

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "docs", "report", "data")
SOC = os.path.join(ROOT, "build", "gemm", "soc")
NAN = "nan"

# Build hash (first 8 hex of the config hash) -> short label, for the builds the report talks about.
PE8_T128 = {"4e52e7f5": "first build", "c49eec09": "150 MHz", "9cf34150": "200 MHz", "1b39ecbf": "250 MHz",
            "1e15de76": "200 MHz explore", "eee29500": "200 MHz aggressive", "71a13954": "map 000",
            "463b0ddf": "map 100"}


# Loading -----------------------------------------------------------------------------------------------------------

def jsonl(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def all_runs():
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "results", "*", "runs.jsonl"))):
        for r in jsonl(f):
            if r.get("status", "ok") == "ok":
                r["_campaign"] = os.path.basename(os.path.dirname(f))
                rows.append(r)
    return rows


def clock_wns(gateware):
    """Per-clock setup WNS from the routed timing summary (Intra Clock Table)."""
    path = os.path.join(gateware, "dupcb_timing.rpt")
    out, inside = {}, False
    if not os.path.exists(path):
        return out
    with open(path, errors="replace") as f:
        for line in f:
            if "Intra Clock Table" in line:
                inside = True
            elif "Inter Clock Table" in line:
                break
            elif inside:
                cells = line.split()
                if len(cells) >= 2:
                    try:
                        out[cells[0]] = float(cells[1])
                    except ValueError:
                        pass
    return out


def builds():
    """One dict per build dir with a summary (config, resources, timing, build time, HLS estimate)."""
    out = {}
    for d in sorted(glob.glob(os.path.join(SOC, "*"))):
        summ = os.path.join(d, "reports", "summary.json")
        if not os.path.exists(summ):
            continue
        with open(summ) as f:
            s = json.load(f)
        soc, hls = s["steps"].get("soc", {}), s["steps"].get("hls", {})
        try:
            with open(os.path.join(d, "stamps", "soc.json")) as f:
                build_s = json.load(f).get("seconds")
        except OSError:
            build_s = None
        wns = clock_wns(os.path.join(d, "gateware"))
        c = s["config"]
        out[s["config_hash"][:8]] = dict(
            id=s["config_hash"][:8], build_id=s["build_id"], cfg=c, k=c["kernel"],
            mhz=c["clocks"]["accel_mhz"], preset=c["vivado"]["preset"],
            map="".join(c["memory_map"][m][-1] for m in "abc"),
            met=bool(soc.get("timing_met")), wns=soc.get("wns_ns"), whs=soc.get("whs_ns"),
            wns_accel=wns.get("main_s7pll_clkout"), wns_pcie=wns.get("main_s7pciephyrxbe_clkout2"),
            wns_sys=wns.get("main_s7mmcm_clkout0"),
            lut=soc.get("lut"), ff=soc.get("ff"), bram=soc.get("bram_tiles"), dsp=soc.get("dsp"),
            klut=soc.get("kernel_lut"), kff=soc.get("kernel_ff"), kbram36=soc.get("kernel_ramb36"),
            kbram18=soc.get("kernel_ramb18"), kdsp=soc.get("kernel_dsp"),
            build_min=None if build_s is None else build_s / 60, hls_ns=hls.get("estimated_clock_ns"),
            hls_ff=hls.get("ff"), peak=2 * c["kernel"]["parallelism_n"] * c["kernel"]["parallelism_m"]
            * c["clocks"]["accel_mhz"] / 1000)
    return out


# Helpers -----------------------------------------------------------------------------------------------------------

def fmt(v, nd=3):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return NAN
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def write(name, header, rows, comment):
    path = os.path.join(OUT, name)
    with open(path, "w", newline="") as f:
        f.write(f"# {comment}\n# generated by docs/report/tools/extract_data.py\n")
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            cells = [fmt(v) for v in r]
            assert not any("," in c for c in cells), f"{name}: comma in {cells} (pgfplots reads no quoted fields)"
            w.writerow(cells)
    print(f"  {name}: {len(rows)} rows")


def label(b):
    k = b["k"]
    s = f"{k['parallelism_n']}x{k['parallelism_m']} t{k['memory_tile_size_n']}x{k['memory_tile_size_m']}"
    s += f" {b['mhz']:g}"
    if k["transposed_a"]:
        s += " tA"
    if b["preset"] != "default":
        s += f" {b['preset'][:3]}"
    if b["map"] != "011":
        s += f" m{b['map']}"
    return s


def runs_by(runs, h):
    return [r for r in runs if r["config_hash"][:8] == h]


def best(runs, h, n=None):
    rs = [r for r in runs_by(runs, h) if n is None or (r["n"], r["k"], r["m"]) == n]
    return max((r["gflops"] for r in rs), default=None)


def pct(part, whole):
    return None if not whole else 100.0 * part / whole


def stall_row(r):
    cyc = r["kernel_cycles"]
    p = r["perf"]
    lat = lambda m: (p[m]["rd_lat_sum"] / p[m]["ar_count"]) if p[m]["ar_count"] else None
    return [pct(p["a"]["r_wait"], cyc), pct(p["b"]["r_wait"], cyc), pct(p["c"]["w_stall"], cyc), lat("a"), lat("b")]


# Tables ------------------------------------------------------------------------------------------------------------

def main():
    os.makedirs(OUT, exist_ok=True)
    runs = all_runs()
    B = builds()
    if not runs or not B:
        raise SystemExit("no results/ or build/gemm/soc/ data: nothing to extract (the committed CSVs stay)")
    print(f"{len(runs)} runs, {len(B)} builds")

    # All builds: configuration, timing, resources, best result.
    rows = []
    for h, b in sorted(B.items(), key=lambda kv: (kv[1]["k"]["parallelism_n"], kv[1]["mhz"], kv[1]["build_id"])):
        g = best(runs, h)
        rows.append([h, label(b), b["k"]["parallelism_n"], b["k"]["parallelism_m"], b["k"]["memory_tile_size_n"],
                     b["k"]["memory_tile_size_m"], int(b["k"]["transposed_a"]), b["mhz"], b["preset"], b["map"],
                     int(b["met"]), b["wns"], b["whs"], b["wns_accel"], b["wns_pcie"], b["wns_sys"],
                     b["lut"] and b["lut"] / 1000, b["ff"] and b["ff"] / 1000, b["bram"], b["dsp"],
                     b["klut"] and b["klut"] / 1000, b["kff"] and b["kff"] / 1000, b["kbram36"], b["kbram18"],
                     b["kdsp"], b["build_min"], b["hls_ns"], b["hls_ff"] and b["hls_ff"] / 1000, g,
                     pct(g, b["peak"]) if g else None, b["peak"]])
    write("builds.csv", ["id", "label", "pn", "pm", "tn", "tm", "ta", "mhz", "preset", "map", "met", "wns", "whs",
                         "wns_accel", "wns_pcie", "wns_sys", "lut_k", "ff_k", "bram", "dsp", "klut_k", "kff_k",
                         "kbram36", "kbram18", "kdsp", "build_min", "hls_ns", "hls_ff_k", "gflops", "pct", "peak"],
          rows, "every Vivado build: config, per-clock WNS (ns), resources (LUT/FF in thousands), best GFLOP/s")

    # The same, pre-formatted for the appendix table (strings, "--" where a build was not run).
    def f(v, nd):
        return "--" if v is None else f"{v:.{nd}f}"
    trows = []
    for r in rows:
        (h, lab, pn, pm, tn, tm, ta, mhz, preset, mp, met, wns, whs, wa, wp, ws, lut, ff, bram, dsp, klut, kff,
         kb36, kb18, kdsp, bmin, hns, hff, g, pc, peak) = r
        trows.append([lab, "yes" if met else "no", f(wa, 3), f(wp, 3), f(ws, 3), f(lut, 1), f(ff, 1), f(bram, 1),
                      f(dsp, 0), f(bmin, 0), f(g, 2), f(pc, 1)])
    write("builds_table.csv", ["label", "met", "wns_accel", "wns_pcie", "wns_sys", "lut_k", "ff_k", "bram", "dsp",
                               "build_min", "gflops", "pct"], trows, "builds.csv formatted for the appendix table")

    # The road to the best result: best GFLOP/s per step of the exploration.
    steps = [("4e52e7f5", "PE 8x8 tile 128 (first build)"), ("e87d80b7", "PE 8x8 tile 256"),
             ("484ad82d", "PE 16x8 tile 256"), ("1a4479b3", "PE 32x8 tile 256"),
             ("2b20290d", "+ transposed A"), ("dc42aa19", "+ tile 512x512"), ("a88777ec", "+ tile 1024x512"),
             ("db5adf1c", "+ 225 MHz (aggressive)")]
    write("progress.csv", ["step", "label", "gflops", "peak", "pct"],
          [[i, lab, best(runs, h), B[h]["peak"] if h in B else 25.6, pct(best(runs, h), B[h]["peak"] if h in B else 25.6)]
           for i, (h, lab) in enumerate(steps)], "best GFLOP/s after each exploration step")

    # PE sweep (tile 256, 200 MHz).
    sizes = [((512, 512, 512), "512"), ((1000, 1008, 1040), "1000x1008x1040"), ((1024, 1024, 1024), "1024"),
             ((2048, 2048, 2048), "2048")]
    pe = {8: "e87d80b7", 16: "484ad82d", 32: "1a4479b3"}
    write("pe_sweep.csv", ["size", "pe8", "pe16", "pe32", "pe8pct", "pe16pct", "pe32pct"],
          [[lab] + [best(runs, pe[p], n) for p in (8, 16, 32)] + [pct(best(runs, pe[p], n), B[pe[p]]["peak"])
                                                                   for p in (8, 16, 32)] for n, lab in sizes],
          "PE sweep: GFLOP/s per size, tile 256x256, 200 MHz")

    # Transposed A vs not (tile 256): GFLOP/s at 2048^3 and the A/B wait shares.
    pairs = [("PE 16x8", "484ad82d", "a9559eb3"), ("PE 32x8", "1a4479b3", "2b20290d")]
    rows = []
    for lab, hn, ht in pairs:
        rn = [r for r in runs_by(runs, hn) if (r["n"], r["k"], r["m"]) == (2048, 2048, 2048)][0]
        rt = [r for r in runs_by(runs, ht) if (r["n"], r["k"], r["m"]) == (2048, 2048, 2048)][0]
        sn, st = stall_row(rn), stall_row(rt)
        rows.append([lab, rn["gflops"], rt["gflops"], sn[0], st[0], sn[1], st[1], rn["perf"]["a"]["ar_count"],
                     rt["perf"]["a"]["ar_count"]])
    write("transposed.csv", ["pe", "g_plain", "g_ta", "await_plain", "await_ta", "bwait_plain", "bwait_ta",
                             "a_bursts_plain", "a_bursts_ta"], rows,
          "transposed A vs plain A at 2048^3, tile 256: GFLOP/s, A/B read-wait cycles in % of kernel cycles")

    # Memory tiles for PE 32x8 transposed A.
    tiles = [("256x256", "2b20290d"), ("256x512", "6e930441"), ("512x256", "de88de4b"), ("512x512", "dc42aa19"),
             ("1024x512", "a88777ec")]
    rows = []
    for lab, h in tiles:
        r4 = [r for r in runs_by(runs, h) if r["n"] == 4096]
        s = stall_row(r4[0]) if r4 else [None] * 5
        rows.append([lab, best(runs, h, (2048,) * 3), best(runs, h, (4096,) * 3), best(runs, h, (8192,) * 3),
                     B[h]["bram"], B[h]["kbram36"], s[0], s[1]])
    write("tiles.csv", ["tile", "g2048", "g4096", "g8192", "bram", "kbram36", "await4096", "bwait4096"], rows,
          "PE 32x8 transposed A, 200 MHz: GFLOP/s per memory tile N x M, BRAM tiles, wait shares at 4096^3")

    # Clock: PE 8x8 t128 and PE 32x8 tA t1024x512.
    rows = []
    for mhz, h, hrun in ((150, "c49eec09", "c49eec09"), (200, "9cf34150", "1e15de76"), (250, "1b39ecbf", "1b39ecbf")):
        b = B[h]
        rows.append(["PE8", mhz, int(b["met"]), b["wns_accel"], b["wns_pcie"], b["wns"], best(runs, hrun),
                     b["hls_ff"] and b["hls_ff"] / 1000, b["ff"] / 1000, b["build_min"]])
    for mhz, h in ((200, "a88777ec"), (225, "6f1f48d5"), (250, "dbb3e8d3")):
        b = B[h]
        rows.append(["PE32", mhz, int(b["met"]), b["wns_accel"], b["wns_pcie"], b["wns"], best(runs, h),
                     b["hls_ff"] and b["hls_ff"] / 1000, b["ff"] / 1000, b["build_min"]])
    write("clock.csv", ["cfg", "mhz", "met", "wns_accel", "wns_pcie", "wns", "gflops", "hls_ff_k", "ff_k",
                        "build_min"], rows,
          "accel clock sweep, default preset (PE8 200 MHz GFLOP/s from the explore build: default missed by 9 ps)")

    # Vivado presets.
    rows = []
    for grp, hs in (("PE 8x8 @ 200", ("9cf34150", "1e15de76", "eee29500")),
                    ("PE 32x8 @ 225", ("6f1f48d5", "8c43d008", "db5adf1c"))):
        for h in hs:
            b = B[h]
            rows.append([grp, b["preset"], int(b["met"]), b["wns_accel"], b["wns_pcie"], b["wns_sys"],
                         b["build_min"], b["lut"] / 1000, best(runs, h)])
    write("presets.csv", ["group", "preset", "met", "wns_accel", "wns_pcie", "wns_sys", "build_min", "lut_k",
                          "gflops"], rows, "Vivado presets: per-clock WNS (ns), build time (min)")

    # Size sweep on the 200 MHz best build: wide tables, one column per (K, M).
    ss = [r for r in runs if r["_campaign"] == "size_sweep"]
    km = sorted({(r["k"], r["m"]) for r in ss})
    ns = sorted({r["n"] for r in ss})
    agg = collections.defaultdict(list)
    for r in ss:
        agg[(r["n"], r["k"], r["m"])].append(r)
    for name, key, what in (("size_kernel.csv", "gflops", "kernel"), ("size_e2e.csv", None, "end to end")):
        rows = []
        for n in ns:
            row = [n]
            for k, m in km:
                rs = agg.get((n, k, m), [])
                if not rs:
                    row.append(None)
                elif key:
                    row.append(statistics.mean(r[key] for r in rs))
                else:
                    row.append(statistics.mean(2.0 * n * k * m / r["e2e_s"] / 1e9 for r in rs))
            rows.append(row)
        write(name, ["n"] + [f"k{k}m{m}" for k, m in km], rows,
              f"size sweep, PE 32x8 tA tile 1024x512 200 MHz: {what} GFLOP/s, mean of the repetitions")
    rows = []
    for (n, k, m), rs in sorted(agg.items()):
        if k == 4096:
            rows.append([ns.index(n), [256, 1024, 4096].index(m), n, m, statistics.mean(r["gflops"] for r in rs)])
    write("size_heat.csv", ["xi", "yi", "n", "m", "gflops"], rows, "size sweep at K = 4096: kernel GFLOP/s over N, M")

    # Host <-> DDR transfer rate per transfer size (every run's A+B upload and C download).
    # The C2H fix (writer enabled once per read) went in at 2026-11-23 20:50; H2C did not change.
    pts = collections.defaultdict(list)
    for r in runs:
        if r.get("h2c_s") and r.get("c2h_s") and r.get("h2c_bytes"):
            pts[("h2c", r["h2c_bytes"])].append(r["h2c_bytes"] / r["h2c_s"] / 1e9)
            c2h = "c2h" if r["timestamp"] >= "2026-11-23T20:50" else "c2h_old"
            pts[(c2h, r["c2h_bytes"])].append(r["c2h_bytes"] / r["c2h_s"] / 1e9)
    for d, what in (("h2c", "H2C (A and B)"), ("c2h", "C2H (C), after the C2H fix"),
                    ("c2h_old", "C2H (C), before the C2H fix (writer enabled per 2 MB chunk)")):
        rows = [[nb / 2**20, statistics.median(v)] for (dd, nb), v in sorted(pts.items()) if dd == d]
        write(f"dma_{d}.csv", ["mib", "gbps"], rows,
              f"{what}: GB/s per transfer size in MiB, from the GEMM runs, median over runs")

    # End-to-end breakdown on the best build.
    rows = []
    for n in (2048, 4096, 8192):
        rs = [r for r in runs_by(runs, "db5adf1c") if r["n"] == n]
        r = rs[0]
        other = r["e2e_s"] - r["kernel_s"] - r["h2c_s"] - r["c2h_s"]
        rows.append([n, r["kernel_s"], r["h2c_s"], r["c2h_s"], other, r["e2e_s"],
                     100 * r["kernel_s"] / r["e2e_s"], 100 * r["h2c_s"] / r["e2e_s"], 100 * r["c2h_s"] / r["e2e_s"],
                     100 * other / r["e2e_s"]])
    write("e2e.csv", ["n", "kernel_s", "h2c_s", "c2h_s", "other_s", "e2e_s", "kernel_pct", "h2c_pct", "c2h_pct",
                      "other_pct"], rows, "end-to-end time of one GEMM on the best build (PE 32x8 tA 225 MHz)")

    # Memory maps (PE 8x8 t128 200 MHz).
    rows = []
    for lab, h in (("A0 B1 C1 (default)", "4e52e7f5"), ("A0 B0 C0", "71a13954"), ("A1 B0 C0", "463b0ddf")):
        r2 = [r for r in runs_by(runs, h) if r["n"] == 2048][0]
        s = stall_row(r2)
        rows.append([lab, best(runs, h, (512,) * 3), best(runs, h, (1024,) * 3), best(runs, h, (2048,) * 3),
                     s[1], s[4]])
    write("memmap.csv", ["map", "g512", "g1024", "g2048", "bwait2048", "blat2048"], rows,
          "memory maps, PE 8x8 tile 128 200 MHz: GFLOP/s; B read wait (% of cycles) and latency (cycles) at 2048^3")

    # Campaigns: time span, points, new Vivado builds, runs.
    rows = []
    for d in sorted(glob.glob(os.path.join(ROOT, "results", "*", "campaign.json"))):
        c = os.path.dirname(d)
        bl, rl = jsonl(os.path.join(c, "builds.jsonl")), jsonl(os.path.join(c, "runs.jsonl"))
        inv = jsonl(os.path.join(c, "invocations.jsonl"))  # start time of campaigns run after 2026-11-23 22:40
        stamps = sorted(r["timestamp"] for r in bl + rl + inv if "timestamp" in r)
        built = {r["build_id"] for r in bl if r.get("stage") == "build" and not r.get("soc", {}).get("skipped", True)}
        points = {r.get("build_id") or r.get("name") for r in bl}
        rows.append([os.path.basename(c), stamps[0][:16] if stamps else None, stamps[-1][:16] if stamps else None,
                     len(points), len(built), len(rl)])
    rows.sort(key=lambda r: r[1] or "")
    write("campaigns.csv", ["campaign", "first", "last", "points", "vivado_builds", "runs"], rows,
          "DSE campaigns: first/last record time, design points, new Vivado builds, run rows")

    # Stall shares across the exploration, at each build's largest size.
    rows = []
    for h, lab in steps:
        rs = [r for r in runs_by(runs, h) if "perf" in r]
        if not rs:
            continue
        r = max(rs, key=lambda r: (r["n"] * r["k"] * r["m"], r["gflops"]))
        rows.append([lab, r["n"]] + stall_row(r))
    write("stalls.csv", ["label", "n", "await", "bwait", "cstall", "alat", "blat"], rows,
          "memory waits in % of kernel cycles (r_wait: kernel ready, no data) and avg read latency (cycles)")


if __name__ == "__main__":
    main()
